package ahab

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

const composeFilesLabel = "com.docker.compose.project.config_files"

const catalogueHeader = `# Generated by "ahab snapshot" from running compose stacks; rerun after
# starting or retiring a stack. Hand edits are overwritten on the next snapshot.
# <docker context> <compose file, relative to DOCKER_DIR>
# Bulk commands act only on these. Others: ahab start <file> [--context X]
`

// Snapshot rewrites DOCKER_DIR/.ahabstacks from the compose stacks running in
// every docker context, printing +/- lines against the previous catalogue.
func Snapshot() error {
	dir, err := getDockerDir()
	if err != nil {
		return err
	}
	out, err := exec.Command("docker", "context", "ls", "--format", "{{.Name}}").Output()
	if err != nil {
		return fmt.Errorf("docker context ls: %w", err)
	}
	stacks, err := runningStacks(strings.Fields(string(out)))
	if err != nil {
		return err
	}

	// A missing or unreadable old catalogue only affects the +/- report.
	old, err := readCatalogue(dir)
	if err != nil && !errors.Is(err, ErrNoCatalogue) {
		fmt.Fprintf(os.Stderr, "previous catalogue unreadable, listing every stack as added: %v\n", err)
	}
	printChanges(old, stacks)

	path := filepath.Join(dir, catalogueFile)
	if err := os.WriteFile(path, []byte(formatCatalogue(dir, stacks)), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %d stacks to %s\n", len(stacks), path)
	return nil
}

// runningStacks returns one Stack per compose file with a running container,
// per context. An unreachable context is an error, not a silent omission.
func runningStacks(contexts []string) ([]Stack, error) {
	var stacks []Stack
	for _, c := range contexts {
		out, err := exec.Command("docker", "--context", c, "ps",
			"--format", `{{.Label "`+composeFilesLabel+`"}}`).Output()
		if err != nil {
			return nil, fmt.Errorf("docker context %s: %w", c, err)
		}
		for _, f := range uniqueLines(out) {
			if strings.Contains(f, ",") {
				fmt.Fprintf(os.Stderr, "skipping %s stack with several compose files: %s\n", c, f)
				continue
			}
			stacks = append(stacks, Stack{Context: c, File: f})
		}
	}
	return stacks, nil
}

// uniqueLines returns the sorted, de-duplicated non-empty lines of out.
func uniqueLines(out []byte) []string {
	var lines []string
	for _, l := range strings.Split(string(out), "\n") {
		if l = strings.TrimSpace(l); l != "" {
			lines = append(lines, l)
		}
	}
	slices.Sort(lines)
	return slices.Compact(lines)
}

// formatCatalogue renders stacks in .ahabstacks format, with paths under dir
// written relative to it.
func formatCatalogue(dir string, stacks []Stack) string {
	var b strings.Builder
	b.WriteString(catalogueHeader)
	for _, s := range stacks {
		file := s.File
		if rel, err := filepath.Rel(dir, file); err == nil && !strings.HasPrefix(rel, "..") {
			file = rel
		}
		fmt.Fprintf(&b, "%-8s %s\n", s.Context, file)
	}
	return b.String()
}

func printChanges(old, current []Stack) {
	for _, s := range current {
		if !slices.Contains(old, s) {
			fmt.Printf("+ %-8s %s\n", s.Context, s.File)
		}
	}
	for _, s := range old {
		if !slices.Contains(current, s) {
			fmt.Printf("- %-8s %s\n", s.Context, s.File)
		}
	}
}
